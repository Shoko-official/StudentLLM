// Generates src/types/api.generated.ts from docs/cloud-api.openapi.yaml.
//
//   node scripts/generate-types.mjs           write the file
//   node scripts/generate-types.mjs --check   fail when the committed file is out of date
//
// Dependency-free apart from the `yaml` dev dependency that the tests already use. It supports the
// JSON Schema subset the contract uses: $ref, type (and type arrays with "null"), enum, const, oneOf,
// object properties, required, additionalProperties, array items.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const SPEC = resolve(here, "../../docs/cloud-api.openapi.yaml");
const OUT = resolve(here, "../src/types/api.generated.ts");

const lit = (value) => JSON.stringify(value);

// `Error` would shadow the global Error class, so the envelope schema is exported as ErrorEnvelope.
const RENAMES = { Error: "ErrorEnvelope" };

function refName(ref) {
  const name = ref.split("/").pop();
  return RENAMES[name] ?? name;
}

function indentOf(level) {
  return "  ".repeat(level);
}

function renderType(schema, level) {
  if (schema === true || schema === undefined) return "unknown";
  if (schema.$ref) return refName(schema.$ref);
  if (schema.oneOf) return schema.oneOf.map((s) => renderType(s, level)).join(" | ");
  if (schema.const !== undefined) return lit(schema.const);
  if (schema.enum) return schema.enum.map(lit).join(" | ");

  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  if (types.length === 0) return "unknown";
  const parts = types.map((t) => renderSingle(t, schema, level));
  return [...new Set(parts)].join(" | ");
}

function renderSingle(type, schema, level) {
  switch (type) {
    case "string":
      return schema.contentEncoding === "binary" ? "Blob" : "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const item = renderType(schema.items, level);
      return /[|&]/.test(item) ? `(${item})[]` : `${item}[]`;
    }
    case "object":
      return renderObject(schema, level);
    default:
      return "unknown";
  }
}

function renderObject(schema, level) {
  const props = schema.properties ?? {};
  const names = Object.keys(props);
  if (names.length === 0) {
    return schema.additionalProperties === true ? "Record<string, unknown>" : "Record<string, never>";
  }
  const required = new Set(schema.required ?? []);
  const lines = names.map((name) => {
    const optional = required.has(name) ? "" : "?";
    return `${indentOf(level + 1)}${name}${optional}: ${renderType(props[name], level + 1)};`;
  });
  if (schema.additionalProperties === true) lines.push(`${indentOf(level + 1)}[key: string]: unknown;`);
  return `{\n${lines.join("\n")}\n${indentOf(level)}}`;
}

function docLine(schema) {
  if (!schema.description) return "";
  const first = String(schema.description).trim().split("\n")[0].replace(/\*\//g, "* /");
  return `/** ${first.length > 160 ? first.slice(0, 157) + "..." : first} */\n`;
}

function pascalToScreaming(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
}

export function generate(spec) {
  const out = [
    "// GENERATED by scripts/generate-types.mjs from docs/cloud-api.openapi.yaml. Do not edit by hand.",
    "// Run `npm run types:generate` after the contract changes; `npm run types:check` (and a test) fails on drift.",
    "",
  ];
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    out.push(docLine(schema) + renderTopLevel(RENAMES[name] ?? name, schema));
  }
  return out.join("\n") + "\n";
}

function renderTopLevel(name, schema) {
  if (schema.enum && schema.type === "string") {
    const constName = pascalToScreaming(name) + "S";
    const values = schema.enum.map(lit).join(", ");
    return `export const ${constName} = [${values}] as const;\nexport type ${name} = (typeof ${constName})[number];\n`;
  }
  return `export type ${name} = ${renderType(schema, 0)};\n`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const spec = parse(readFileSync(SPEC, "utf8"));
  const text = generate(spec);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      // missing file counts as out of date
    }
    if (current !== text) {
      console.error("src/types/api.generated.ts is out of date. Run `npm run types:generate`.");
      process.exit(1);
    }
    console.log("src/types/api.generated.ts is up to date");
  } else {
    writeFileSync(OUT, text);
    console.log("wrote src/types/api.generated.ts");
  }
}
